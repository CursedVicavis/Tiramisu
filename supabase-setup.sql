-- 1. Tabla principal: Eventos
create table if not exists public."Eventos" (
  id                          bigint generated by default as identity primary key,
  evento                      text        not null,
  descripcion                 text        default '',
  fecha_inicio                date        not null,
  fecha_estimada_finalizacion date        not null,
  fecha_finalizacion          date        default null,
  user_id                     uuid        references auth.users(id) on delete cascade default auth.uid(),
  created_at                  timestamptz not null default now()
);

-- 2. Tabla de tareas y recordatorios: Eventos_Detalles
create table if not exists public."Eventos_Detalles" (
  id            bigint generated by default as identity primary key,
  id_evento     bigint      not null references public."Eventos"(id) on delete cascade,
  nombre        text        not null default '',
  detalle       text        default '',
  recordatorios jsonb       not null default '[]'::jsonb,
  completada    boolean     not null default false,
  created_at    timestamptz not null default now()
);

-- 3. Índices recomendados
create index if not exists eventos_created_at_idx
  on public."Eventos" (created_at desc);

create index if not exists eventos_user_id_idx
  on public."Eventos" (user_id);

create index if not exists eventos_detalles_id_evento_idx
  on public."Eventos_Detalles" (id_evento);

-- 4. Habilitar Row Level Security (RLS)
alter table public."Eventos" enable row level security;
alter table public."Eventos_Detalles" enable row level security;

-- 5. Políticas RLS para usuarios autenticados
create policy "Usuarios gestionan sus propios eventos"
  on public."Eventos"
  for all
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Usuarios gestionan los detalles de sus eventos"
  on public."Eventos_Detalles"
  for all
  to authenticated
  using (
    exists (
      select 1 from public."Eventos" e
      where e.id = "Eventos_Detalles".id_evento
        and e.user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from public."Eventos" e
      where e.id = "Eventos_Detalles".id_evento
        and e.user_id = auth.uid()
    )
  );

-- ============================================================
-- 6. Tabla de Proyectos, Seguimiento, Ideas y Comunidad
-- ============================================================
create table if not exists public."Proyectos" (
  id              bigint generated by default as identity primary key,
  titulo          text        not null,
  marca_categoria text        default '',
  descripcion     text        default '',
  notas           text        default '',
  estado          text        not null default 'por_ver',
  enlaces         jsonb       not null default '[]'::jsonb,
  imagenes        jsonb       not null default '[]'::jsonb,
  items           jsonb       not null default '[]'::jsonb,
  recordatorios   jsonb       not null default '[]'::jsonb,
  blog            jsonb       not null default '[]'::jsonb,
  es_publico      boolean     not null default false,
  likes           integer     not null default 0,
  feedback        jsonb       not null default '[]'::jsonb,
  autor_email     text        default '',
  user_id         uuid        references auth.users(id) on delete cascade default auth.uid(),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists proyectos_created_at_idx
  on public."Proyectos" (created_at desc);

create index if not exists proyectos_es_publico_idx
  on public."Proyectos" (es_publico);

alter table public."Proyectos" enable row level security;

-- Usuarios autenticados pueden ver sus propios proyectos o los proyectos públicos de la comunidad
create policy "Ver proyectos propios o publicos"
  on public."Proyectos"
  for select
  to authenticated
  using (auth.uid() = user_id or es_publico = true);

create policy "Insertar proyectos propios"
  on public."Proyectos"
  for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Actualizar proyectos propios o dar feedback en publicos"
  on public."Proyectos"
  for update
  to authenticated
  using (auth.uid() = user_id or es_publico = true)
  with check (auth.uid() = user_id or es_publico = true);

create policy "Eliminar proyectos propios"
  on public."Proyectos"
  for delete
  to authenticated
  using (auth.uid() = user_id);

